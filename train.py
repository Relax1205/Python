import tensorflow as tf  # Импортируем TensorFlow — фреймворк для машинного обучения
from tensorflow import keras  # Импортируем Keras — высокоуровневое API для работы с нейросетями в TensorFlow

# === ЗАГРУЗКА ДАННЫХ ===
# Загружаем набор данных MNIST (70 000 изображений рукописных цифр 28x28 пикселей)
(x_train, y_train), (x_test, y_test) = keras.datasets.mnist.load_data()

# Нормализация данных:  
# - Данные представлены в виде 28x28 пиксельных изображений со значениями от 0 до 255
# - Делим каждое значение на 255, чтобы перевести диапазон в 0-1 (ускоряет обучение)
x_train, x_test = x_train / 255.0, x_test / 255.0  

# === СОЗДАНИЕ МОДЕЛИ НЕЙРОСЕТИ ===
model = keras.Sequential([  # Создаём последовательную модель (последовательность слоёв)
    
    # Входной слой: Преобразуем изображение 28x28 в одномерный вектор из 784 чисел
    keras.layers.Flatten(input_shape=(28, 28)),  
    
    # Скрытый слой: Полносвязный слой с 128 нейронами и функцией активации ReLU
    keras.layers.Dense(128, activation='relu'),  
    
    # Выходной слой: 10 нейронов (по количеству классов 0-9), softmax даёт вероятности
    keras.layers.Dense(10, activation='softmax')  
])

# === КОМПИЛЯЦИЯ И ОБУЧЕНИЕ МОДЕЛИ ===
model.compile(
    optimizer='adam',  # Оптимизатор Adam — популярный выбор для обучения нейросетей
    loss='sparse_categorical_crossentropy',  # Функция потерь для классификации
    metrics=['accuracy']  # Метрика: точность (доля верных предсказаний)
)

# Запуск процесса обучения (5 эпох, каждая проходит по всем обучающим данным)
model.fit(x_train, y_train, epochs=5)

# === СОХРАНЕНИЕ МОДЕЛИ ===
model.save('mnist_model.h5')  # Сохраняем обученную модель в файл mnist_model.h5
print("Модель сохранена в 'mnist_model.h5'")  # Выводим сообщение об успешном сохранении
