import tensorflow as tf  # Импортируем TensorFlow для работы с нейросетями
from tensorflow import keras  # Подключаем Keras — удобное API для нейросетей
import numpy as np  # Библиотека для работы с массивами
import matplotlib.pyplot as plt  # Графическая библиотека для визуализации
import cv2  # OpenCV — используется для обработки изображений и взаимодействия с пользователем

# === ЗАГРУЗКА ОБУЧЕННОЙ МОДЕЛИ ===
# Загружаем ранее сохранённую обученную модель, которая умеет распознавать цифры
model = keras.models.load_model('mnist_model.h5')

# === СОЗДАЁМ ХОЛСТ ДЛЯ РИСОВАНИЯ ===
# Создаём белый квадрат размером 280x280 пикселей, где пользователь сможет нарисовать цифру
canvas = np.ones((280, 280), dtype=np.uint8) * 255  # 255 — белый цвет

# === ФУНКЦИЯ ДЛЯ РИСОВАНИЯ МЫШЬЮ ===
def draw(event, x, y, flags, param):
    """
    Функция обработки событий OpenCV для рисования мышью.
    Позволяет рисовать чёрные кружки на белом холсте.
    """
    # Если нажата левая кнопка мыши или перемещение мыши с зажатой кнопкой:
    if event == cv2.EVENT_LBUTTONDOWN or (event == cv2.EVENT_MOUSEMOVE and flags == cv2.EVENT_FLAG_LBUTTON):
        cv2.circle(canvas, (x, y), 10, (0, 0, 0), -1)  # Рисуем круг радиусом 10 пикселей чёрным цветом

# Создаём окно OpenCV и назначаем функцию обработки событий мыши
cv2.namedWindow('Рисуйте цифру и нажмите Enter')
cv2.setMouseCallback('Рисуйте цифру и нажмите Enter', draw)

# === ОСНОВНОЙ ЦИКЛ РИСОВАНИЯ ===
while True:
    cv2.imshow('Рисуйте цифру и нажмите Enter', canvas)  # Отображаем холст
    key = cv2.waitKey(1)  # Ожидаем нажатие клавиши
    if key == 13:  # Код клавиши Enter (пользователь завершил рисование)
        break

cv2.destroyAllWindows()  # Закрываем окно OpenCV

# === ПРЕОБРАЗОВАНИЕ РИСУНКА ДЛЯ НЕЙРОСЕТИ ===
# Масштабируем изображение 280x280 → 28x28, так как нейросеть обучена на таких размерах
img = cv2.resize(canvas, (28, 28))

# Если изображение имеет 3 канала (цветное), конвертируем в оттенки серого
if len(img.shape) == 3:
    img = cv2.cvtColor(img, cv2.COLOR_BGR2GRAY)

# Нормализуем изображение (приводим пиксели к диапазону 0-1)
img = img / 255.0  

# Инвертируем изображение: фон становится чёрным (0), а цифра белой (1)
img = 1 - img  

# Добавляем размерность (из 28x28 делаем 1x28x28), так как нейросеть ожидает 3D-массив
img = img.reshape(1, 28, 28)

# === ПРЕДСКАЗАНИЕ НЕЙРОСЕТИ ===
prediction = model.predict(img)  # Нейросеть делает предсказание
digit = np.argmax(prediction)  # Находим индекс наибольшего значения (это и есть распознанная цифра)

# === ВИЗУАЛИЗАЦИЯ РЕЗУЛЬТАТА ===
plt.imshow(img.reshape(28, 28), cmap='gray')  # Отображаем нарисованную цифру
plt.title(f'Распознанная цифра: {digit}')  # Выводим распознанный результат
plt.show()  # Показываем график
